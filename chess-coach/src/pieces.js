export function detectOpening(sanHistory) {
  let matched = 'Custom / Unclassified Opening';
  let bestLen = 0;
  for (const op of OPENINGS) {
    if (sanHistory.length >= op.prefix.length && op.prefix.length > bestLen) {
      let ok = true;
      for (let i = 0; i < op.prefix.length; i++) {
        if (sanHistory[i] !== op.prefix[i]) {
          ok = false;
          break;
        }
      }
      if (ok) {
        matched = op.name;
        bestLen = op.prefix.length;
      }
    }
  }
  return { name: matched, bookPly: bestLen };
}

